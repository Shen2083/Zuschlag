"""Seed a demo tenant for the Quote Studio (local development only).

    DATABASE_URL=postgresql+asyncpg://zuschlag_app:...@localhost:5432/zuschlag \
        uv run python scripts/seed_demo.py

Creates one tenant with a small SAP material and customer master, an outbound
partner profile, and three quotes generated by the real RFQ pipeline from the
German and English test inquiries. The LLM step replays the recorded
extractions (tests/fixtures/rfq/*.extraction.json) instead of calling a model,
and matching uses the test suite's concept embedder, so no model download or
API key is needed. Prints the tenant id to put into the web app's DEV_TENANT_ID.
"""

from __future__ import annotations

import asyncio
import os
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # for `tests.rfq_support`
os.environ.setdefault("EMBEDDING_PROVIDER", "hashing")

from sqlalchemy import select
from tests.rfq_support import ConceptEmbedder, golden_extraction, rfq_text, seed_catalog

from zuschlag_api.api.routes.quotes import pipeline_config
from zuschlag_api.core.config import get_settings
from zuschlag_api.db.session import tenant_session
from zuschlag_api.llm.client import ZeroRetentionLLMClient
from zuschlag_api.llm.providers import FakeProvider
from zuschlag_api.models import (
    Customer,
    CustomerSalesArea,
    Rfq,
    RfqSource,
    Tenant,
)
from zuschlag_api.rfq.pipeline import QuotePipeline

DEMO_TENANT = uuid.UUID(os.environ.get("DEMO_TENANT_ID", "5e1d0c3a-7b1f-4c2e-9a55-0d3f6c8b2a10"))
PROFILE = {
    "mandt": "800",
    "docrel": "750",
    "status": "30",
    "direct": "1",
    "sender_port": "SAPERP",
    "sender_partner_type": "LS",
    "sender_partner": "CLNT800",
    "receiver_port": "ZUSCHLAG",
    "receiver_partner_type": "LS",
    "receiver_partner": "ZUSCHLAGAI",
    "vendor_number": "0000200000",
    "vendor_name": "Müller Metallbau GmbH",
}
CUSTOMERS = [
    ("0000100077", "Rechenzentrum Nord GmbH", "Hafenstraße 12", "20457", "Hamburg", "NT30"),
    ("0000100099", "Nordwind Marine AG", "Am Kai 3", "24103", "Kiel", "NT14"),
]
INQUIRIES = [("rack_de", None), ("catalog_de", "100077"), ("worktable_en", "100099")]


async def main() -> None:
    settings = get_settings().model_copy(update={"rfq_dense_floor": 0.0, "rfq_dense_ceiling": 1.0})
    async with tenant_session(DEMO_TENANT) as s:
        if await s.scalar(select(Tenant).where(Tenant.tenant_id == DEMO_TENANT)):
            print(f"demo tenant already seeded: DEV_TENANT_ID={DEMO_TENANT}")
            return
        s.add(
            Tenant(
                tenant_id=DEMO_TENANT,
                name="Müller Metallbau GmbH",
                sap_client="800",
                sap_sales_org="1000",
                sap_outbound_profile=PROFILE,
            )
        )
        await s.flush()
        embedder = ConceptEmbedder()
        await seed_catalog(s, embedder)
        for kunnr, name, street, plz, city, zterm in CUSTOMERS:
            c = Customer(
                kunnr=kunnr, name1=name, street=street, postal_code=plz, city=city, country="DE"
            )
            s.add(c)
            await s.flush()
            s.add(
                CustomerSalesArea(
                    customer_id=c.id,
                    sales_org="1000",
                    distribution_channel="10",
                    division="00",
                    currency="EUR",
                    payment_terms=zterm,
                )
            )
        await s.flush()

        for fixture, customer in INQUIRIES:
            llm = ZeroRetentionLLMClient(
                FakeProvider(model=settings.llm_model, structured=golden_extraction(fixture))
            )
            config = pipeline_config(settings)
            pipeline = QuotePipeline(s, llm=llm, embedder=embedder, config=config)
            quote = await pipeline.generate(
                rfq_text(fixture), actor_id="demo-seed", ip_sha256=None, customer_ref=customer
            )
            rfq = await s.scalar(select(Rfq).where(Rfq.id == quote.rfq_id))
            if rfq is not None:
                rfq.source = RfqSource.EMAIL
            print(f"{quote.quote_number}  {quote.status.value:13} {fixture}")
    print(f"DEV_TENANT_ID={DEMO_TENANT}")


if __name__ == "__main__":
    asyncio.run(main())
